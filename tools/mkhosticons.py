def rows(art):
    lines = [l for l in art.strip("\n").split("\n")]
    assert len(lines) <= 16, "too tall"
    while lines and lines[0] == "." * 16:
        lines.pop(0)
    top = (16 - len(lines)) // 2             # centred, top to bottom
    lines = ["." * 16] * top + lines + ["." * 16] * (16 - len(lines) - top)
    out = []
    for l in lines:
        assert len(l) == 16, "a row is not 16 wide: %r" % l
        out.append(sum(1 << (15 - x) for x, c in enumerate(l) if c == "#"))
    return out


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "..", "app", "pthosticons.h")
    with open(path, "w") as f:
        f.write("/* pthosticons.h - made by tools/mkhosticons.py: the Start view's server icons */\n")
        f.write("#ifndef PTHOSTICONS_H\n#define PTHOSTICONS_H\n")
        f.write("// a server's THostEntry::iIcon: 0 is its initial, 1.. these, in this order\n")
        f.write("// (saved in Hosts.dat: add at the end, never reorder)\n")
        f.write("const TInt KPtHostIconCount = %d;\n" % len(ICONS))
        f.write("static const TUint16 KPtHostIconBits[%d][16] =\n\t{\n" % len(ICONS))
        for name, art in ICONS:
            f.write("\t{ " + ", ".join("0x%04x" % r for r in rows(art)) + " },   // " + name + "\n")
        f.write("\t};\n")
        f.write("static const TText* const KPtHostIconNames[%d] =\n\t{ " % len(ICONS))
        f.write(", ".join('_S("%s")' % name for name, _ in ICONS))
        f.write(" };\n#endif\n")
    if "--png" in sys.argv:
        from PIL import Image
        img = Image.new("RGB", (len(ICONS) * 26 + 6, 32), "white")
        for i, (_, art) in enumerate(ICONS):
            for dy in range(24):
                for dx in range(24):
                    img.putpixel((4 + i * 26 + dx, 4 + dy), (51, 51, 204))
            for y, r in enumerate(rows(art)):
                for x in range(16):
                    if r & (1 << (15 - x)):
                        img.putpixel((8 + i * 26 + x, 8 + y), (255, 255, 255))
        img = img.resize((img.width * 3, img.height * 3), Image.NEAREST)
        img.save(sys.argv[sys.argv.index("--png") + 1])


if __name__ == "__main__":
    main()
