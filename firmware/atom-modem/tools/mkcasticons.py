#!/usr/bin/env python3
# mkcasticons.py - the PsiCast viewer's "Series 7" icons for the firmware:
# src/cast/iconmatch.js and src/cast/s7icons.json gzipped, as C arrays in
# src/cast/casticons.h (committed, so a build needs no Python). The viewer
# fetches them only when the Series 7 theme is chosen, from
# /screen/iconmatch.js and /screen/s7icons.json. Run it after changing
# either file (s7icons.json comes from tools/s7icons.py):
#   python3 tools/mkcasticons.py
# MIT licence (see LICENSE at the top of the repository).
import gzip, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src", "cast")


def carray(name, data):
    lines = []
    for i in range(0, len(data), 20):
        lines.append("\t" + ",".join("0x%02x" % b for b in data[i:i + 20]) + ",")
    return "static const unsigned char %s[] = {\n%s\n\t};\nstatic const unsigned %sLen = %d;\n" % (
        name, "\n".join(lines), name, len(data))


def main():
    js = open(os.path.join(SRC, "iconmatch.js"), "rb").read()
    pack = open(os.path.join(SRC, "s7icons.json"), "rb").read()
    jsz = gzip.compress(js, compresslevel=9, mtime=0)
    packz = gzip.compress(pack, compresslevel=9, mtime=0)
    out = ["// casticons.h - generated by tools/mkcasticons.py: do not edit.",
           "// The PsiCast viewer's Series 7 icon matcher and icon pack (both gzipped).",
           "// The pictures in kCastS7IconsGz are Psion's, from its ROMs.",
           "#ifndef ATOM_CASTICONS_H", "#define ATOM_CASTICONS_H", "",
           carray("kCastIconMatchGz", jsz), carray("kCastS7IconsGz", packz), "#endif", ""]
    open(os.path.join(SRC, "casticons.h"), "w").write("\n".join(out))
    print("casticons.h: iconmatch.js %d bytes (%d gzipped), s7icons.json %d bytes (%d gzipped)"
          % (len(js), len(jsz), len(pack), len(packz)))


if __name__ == "__main__":
    sys.exit(main())
