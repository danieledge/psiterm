#!/usr/bin/env python3
# mkcasticons.py - the PsiCast viewer's "Series 7" icons for the firmware:
# src/cast/iconmatch.js and src/cast/s7icons.json gzipped, as C arrays in
# src/cast/casticons.h (committed, so a build needs no Python). The viewer
# fetches them only when the Series 7 theme is chosen, from
# /screen/iconmatch.js and /screen/s7icons.json. Run it after changing
# either file (s7icons.json comes from tools/s7icons.py). The "Modern"
# theme's pack, src/cast/modicons.json (tools/modicons.py), the same way as
# kCastModIconsGz for /screen/modicons.json, if it is there (if not, an empty
# one: the route answers 404 and the theme has no pictures). If a local pack
# is there too, src/cast/modicons.local.json (not in the repository: pictures
# of programs of one's own, made the same way), the two are merged (one
# palette of 256 colours at most, the local pack's indices moved to suit) into
# src/cast/casticons_local.h, which casticons.h includes in place of its own
# kCastModIconsGz when it is there; casticons.h itself always holds the
# public pack only. Also the 5mx's face
# for full screen, src/cast/silk5mx.jpg (as it is, /screen/silk5mx.jpg): the
# Psion Web Emulator's 5mx skin with the screen area cut out - "Psion Web
# Emulator by Joe Haines - https://joehaines.com/psion".
#   python3 tools/mkcasticons.py
# MIT licence (see LICENSE at the top of the repository).
import gzip, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src", "cast")


def carray(name, data):
    lines = []
    for i in range(0, len(data), 20):
        lines.append("\t" + ",".join("0x%02x" % b for b in data[i:i + 20]) + ",")
    return "static const unsigned char %s[] = {\n%s\n\t};\nstatic const unsigned %sLen = %d;\n" % (
        name, "\n".join(lines), name, len(data))


def merge_packs(pub, loc):
    """one pack: pub's pictures, then loc's (unless pub has one of that
    name), with one palette; an error if it would be over 256 colours"""
    import base64
    a, b = json.loads(pub), json.loads(loc)
    for p in (a, b):
        if p.get("format") != "psicast-iconpack" or p.get("version") != 2:
            raise SystemExit("mkcasticons: not a version 2 icon pack")
    def used(p):
        idx = set()
        for e in p["icons"]:
            idx.update(base64.b64decode(e["c"]))
        return idx
    pa, pb = base64.b64decode(a["palette"]), base64.b64decode(b["palette"])
    ua, ub = used(a), used(b)
    n = max(ua) + 1 if ua else 0           # pub's palette keeps its indices
    pal = [bytes(pa[3 * i:3 * i + 3]) for i in range(n)]
    at = {}
    for i, rgb in enumerate(pal):
        at.setdefault(rgb, i)
    def add(rgb):
        if rgb not in at:
            at[rgb] = len(pal); pal.append(rgb)
        return at[rgb]
    remap = {i: add(bytes(pb[3 * i:3 * i + 3])) for i in sorted(ub)}
    if len(pal) > 256:
        raise SystemExit("mkcasticons: the merged Modern pack has %d colours (256 at most)" % len(pal))
    names = {e["n"] for e in a["icons"]}
    icons = list(a["icons"])
    for e in b["icons"]:
        if e["n"] in names:
            continue
        e = dict(e, c=base64.b64encode(bytes(remap[c] for c in base64.b64decode(e["c"]))).decode())
        icons.append(e)
    flat = b"".join(pal) + bytes(3 * (256 - len(pal)))
    out = {"format": "psicast-iconpack", "version": 2, "palette": base64.b64encode(flat).decode(), "icons": icons}
    return json.dumps(out, separators=(",", ":")).encode() + b"\n", len(icons) - len(a["icons"]), len(pal)


def main():
    js = open(os.path.join(SRC, "iconmatch.js"), "rb").read()
    pack = open(os.path.join(SRC, "s7icons.json"), "rb").read()
    face = open(os.path.join(SRC, "silk5mx.jpg"), "rb").read()
    modp = os.path.join(SRC, "modicons.json")
    mod = open(modp, "rb").read() if os.path.exists(modp) else b""
    modz = gzip.compress(mod, compresslevel=9, mtime=0) if mod else b""
    jsz = gzip.compress(js, compresslevel=9, mtime=0)
    packz = gzip.compress(pack, compresslevel=9, mtime=0)
    out = ["// casticons.h - generated by tools/mkcasticons.py: do not edit.",
           "// The PsiCast viewer's icon matcher and its icon packs (gzipped): Series 7, Modern",
           "// (kCastModIconsGzLen 0: no Modern pack, the route answers 404).",
           "// The pictures in kCastS7IconsGz are Psion's, from its ROMs.",
           "// kCastSilk5mx: the 5mx's face (JPEG), from the Psion Web Emulator by Joe Haines -",
           "// https://joehaines.com/psion - with the screen area cut out.",
           "#ifndef ATOM_CASTICONS_H", "#define ATOM_CASTICONS_H", "",
           carray("kCastIconMatchGz", jsz), carray("kCastS7IconsGz", packz),
           "// (casticons_local.h, if it is there: the Modern pack with local pictures added)",
           "#if defined(__has_include)", "#if __has_include(\"casticons_local.h\")", "#define CAST_MODICONS_LOCAL 1",
           "#include \"casticons_local.h\"", "#endif", "#endif", "#ifndef CAST_MODICONS_LOCAL",
           carray("kCastModIconsGz", modz) if modz else
           "static const unsigned char kCastModIconsGz[] = { 0 };\nstatic const unsigned kCastModIconsGzLen = 0;\n",
           "#endif",
           carray("kCastSilk5mx", face), "#endif", ""]
    open(os.path.join(SRC, "casticons.h"), "w").write("\n".join(out))
    locp, loch = os.path.join(SRC, "modicons.local.json"), os.path.join(SRC, "casticons_local.h")
    if mod and os.path.exists(locp):
        merged, nloc, ncol = merge_packs(mod, open(locp, "rb").read())
        mz = gzip.compress(merged, compresslevel=9, mtime=0)
        open(loch, "w").write("\n".join([
            "// casticons_local.h - generated by tools/mkcasticons.py: do not edit, do not commit.",
            "// The Modern icon pack with the local pack's pictures added (included by casticons.h).",
            "#ifndef ATOM_CASTICONS_LOCAL_H", "#define ATOM_CASTICONS_LOCAL_H", "",
            carray("kCastModIconsGz", mz), "#endif", ""]))
        print("casticons_local.h: the Modern pack and %d local pictures, %d colours, %d bytes (%d gzipped)"
              % (nloc, ncol, len(merged), len(mz)))
    elif os.path.exists(loch):
        os.remove(loch)
        print("casticons_local.h: removed (no local pack)")
    print("casticons.h: iconmatch.js %d bytes (%d gzipped), s7icons.json %d bytes (%d gzipped), modicons.json %s, silk5mx.jpg %d bytes"
          % (len(js), len(jsz), len(pack), len(packz),
             "%d bytes (%d gzipped)" % (len(mod), len(modz)) if mod else "missing", len(face)))


if __name__ == "__main__":
    sys.exit(main())
