#!/usr/bin/env python3
# mkcastpage.py - PsiCast's viewer page for the firmware: src/cast/viewer.html
# gzipped, the Home Screen icons (drawn here with Pillow) and the web app
# manifest, as C arrays in src/cast/castpage.h (which is committed, so a
# build needs neither Python nor Pillow). Run it after changing the page:
#   python3 tools/mkcastpage.py
# MIT licence (see LICENSE at the top of the repository).
import gzip, io, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src", "cast")


def icon(size):
    from PIL import Image, ImageDraw
    s = size * 4                                   # drawn big, then scaled down (smooth edges)
    im = Image.new("RGB", (s, s), (21, 24, 27))
    d = ImageDraw.Draw(im)
    # the 5mx's screen: a wide LCD in its bezel
    m = s * 0.12
    bez = (m, s * 0.27, s - m, s * 0.73)
    d.rounded_rectangle(bez, radius=s * 0.05, fill=(46, 51, 56))
    lcd = (bez[0] + s * 0.035, bez[1] + s * 0.035, bez[2] - s * 0.035, bez[3] - s * 0.035)
    d.rectangle(lcd, fill=(186, 196, 164))
    ink = (27, 36, 26)
    # a few lines of "text" and a title bar
    lw = lcd[2] - lcd[0]
    d.rectangle((lcd[0], lcd[1], lcd[2], lcd[1] + s * 0.045), fill=ink)
    y = lcd[1] + s * 0.085
    for frac in (0.78, 0.6, 0.7, 0.42):
        d.rectangle((lcd[0] + s * 0.03, y, lcd[0] + s * 0.03 + lw * frac * 0.85, y + s * 0.026), fill=ink)
        y += s * 0.052
    # the cast: three arcs over the screen
    cx, cy = s * 0.5, s * 0.255
    for i, r in enumerate((0.07, 0.12, 0.17)):
        rr = s * r
        d.arc((cx - rr, cy - rr, cx + rr, cy + rr), 215, 325, fill=(127, 176, 105), width=int(s * 0.03))
    im = im.resize((size, size), Image.LANCZOS)
    out = io.BytesIO()
    im.save(out, "PNG", optimize=True)
    return out.getvalue()


def carray(name, data):
    lines = []
    for i in range(0, len(data), 20):
        lines.append("\t" + ",".join("0x%02x" % b for b in data[i:i + 20]) + ",")
    return "static const unsigned char %s[] = {\n%s\n\t};\nstatic const unsigned %sLen = %d;\n" % (
        name, "\n".join(lines), name, len(data))


def main():
    html = open(os.path.join(SRC, "viewer.html"), "rb").read()
    page = gzip.compress(html, compresslevel=9, mtime=0)
    manifest = json.dumps({
        "name": "PsiCast", "short_name": "PsiCast", "start_url": "/screen", "scope": "/screen",
        "display": "standalone", "orientation": "any", "background_color": "#15181b", "theme_color": "#15181b",
        "icons": [{"src": "/screen/icon.png", "sizes": "180x180", "type": "image/png"},
                  {"src": "/screen/icon-512.png", "sizes": "512x512", "type": "image/png"}]
    }, separators=(",", ":"))
    out = ["// castpage.h - generated by tools/mkcastpage.py from viewer.html: do not edit.",
           "// PsiCast's viewer page (gzipped), its Home Screen icons and its manifest.",
           "// MIT licence (see LICENSE at the top of the repository).",
           "#ifndef ATOM_CASTPAGE_H", "#define ATOM_CASTPAGE_H", "",
           carray("kCastPageGz", page), carray("kCastIcon180", icon(180)), carray("kCastIcon512", icon(512)),
           "static const char kCastManifest[] = %s;" % json.dumps(manifest), "", "#endif", ""]
    open(os.path.join(SRC, "castpage.h"), "w").write("\n".join(out))
    print("castpage.h: page %d bytes (%d gzipped)" % (len(html), len(page)))


if __name__ == "__main__":
    sys.exit(main())
